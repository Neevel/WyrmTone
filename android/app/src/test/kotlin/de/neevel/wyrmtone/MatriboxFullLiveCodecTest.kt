    @Test fun `parameter writes reproduce first and last captured message of all groups`() {
        assertEquals(46, groups.size)
        for (g in groups) {
            val slot = slots[g.slot - 1]
            assertEquals("slot ${g.slot} idx ${g.index} first", g.firstHex, hex(MatriboxFullLiveCodec.encode(FullLiveOperation.Parameter(slot, g.code, g.index, g.first, "x"))))
            assertEquals("slot ${g.slot} idx ${g.index} last", g.lastHex, hex(MatriboxFullLiveCodec.encode(FullLiveOperation.Parameter(slot, g.code, g.index, g.last, "x"))))
        }
        assertEquals(setOf(1, 2, 3, 4, 5, 6, 7, 8, 9), groups.map { it.slot }.toSet())
        assertTrue(groups.any { it.last < 0f })
        assertTrue(groups.any { it.last != Math.round(it.last).toFloat() })
    }

    @Test fun `model selects reproduce every captured message on every slot`() {
        assertEquals(11, selects.size)
        for ((slot, code, expected) in selects) {
            assertEquals("slot $slot", expected, hex(MatriboxFullLiveCodec.encode(FullLiveOperation.ModelSelect(slots[slot - 1], code, "x"))))
        }
        assertEquals(setOf(1, 2, 3, 4, 5, 6, 7, 8, 9), selects.map { it.first }.toSet())
    }

    @Test fun `block toggles for nine slots and both directions equal captured control changes`() {
        for (slot in slots) {
            for (enabled in listOf(true, false)) {
                assertTrue("${slot.name} $enabled", hex(MatriboxFullLiveCodec.encode(FullLiveOperation.BlockToggle(slot, enabled))) in captureControlChanges)
            }
        }
        assertEquals(listOf(0x30, 0x31, 0x32, 0x33, 0x34, 0x35, 0x36, 0x37, 0x38), slots.map { it.controller })
    }

    @Test fun `the fixed plan equals exactly the 25 captured messages, in order (Kotlin == Dart == capture)`() {
        assertEquals(25, MatriboxFullLivePlan.operations.size)
        assertEquals(plannedMessages, MatriboxFullLivePlan.operations.map { hex(MatriboxFullLiveCodec.encode(it)) })
    }

    @Test fun `plan composition is 9 model selects, 14 parameter writes, 2 toggles, no store or metadata`() {
        val ops = MatriboxFullLivePlan.operations
        assertEquals(9, ops.count { it is FullLiveOperation.ModelSelect })
        assertEquals(14, ops.count { it is FullLiveOperation.Parameter })
        assertEquals(2, ops.count { it is FullLiveOperation.BlockToggle })
        assertEquals(setOf(ChainSlot.FX1, ChainSlot.FX2), ops.filterIsInstance<FullLiveOperation.BlockToggle>().map { it.slot }.toSet())
        for (op in ops) {
            val message = MatriboxFullLiveCodec.encode(op)
            MatriboxFullLiveCodec.validate(message)
            if (message.size > 3) assertEquals(0x10, message[9].toInt()) // never 12 11 / 12 12
        }
    }

    @Test fun `validate refuses metadata, commit and malformed messages`() {
        val store = bytes("f021257f514d45321212000002000000000000f7")
        assertThrows(IllegalArgumentException::class.java) { MatriboxFullLiveCodec.validate(store) }
        val metadata = MatriboxFullLiveCodec.encode(FullLiveOperation.ModelSelect(ChainSlot.FX1, 0x03000000, "x")).copyOf()
        metadata[9] = 0x11
        assertThrows(IllegalArgumentException::class.java) { MatriboxFullLiveCodec.validate(metadata) }
        val badSlot = MatriboxFullLiveCodec.encode(FullLiveOperation.ModelSelect(ChainSlot.FX1, 0x03000000, "x")).copyOf()
        badSlot[10] = 0x0a
        assertThrows(IllegalArgumentException::class.java) { MatriboxFullLiveCodec.validate(badSlot) }
        assertThrows(IllegalArgumentException::class.java) { MatriboxFullLiveCodec.validate(byteArrayOf(0xb1.toByte(), 0x39, 0x00)) }
        assertThrows(IllegalArgumentException::class.java) { MatriboxFullLiveCodec.validate(byteArrayOf(0xb1.toByte(), 0x30, 0x40)) }
        assertThrows(IllegalArgumentException::class.java) {
            MatriboxFullLiveCodec.encode(FullLiveOperation.Parameter(ChainSlot.FX1, 0x03000000, 0, Float.NaN, "x"))
        }
        assertFalse(hex(MatriboxFullLiveCodec.encode(MatriboxFullLivePlan.operations[0])).isEmpty())
    }
